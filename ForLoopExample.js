// Print 1 to 10 using a for loop

for(let i = 1; i <= 10; i++){
    console.log(i);
}

//print all the letters in the given string using for loop
let str1 = 'Let us learn JavaScript';

for(let i = 0; i < str1.length; i++){
    console.log(str1[i]);
}

// For each loop example
let arrNames = ['John', 'Jane', 'Jack', 'Jill'];

for(let name of arrNames){
    console.log(name)
}

let arrNumers = [1, 2, 3, 4, 5];

for(let num of arrNumers){
    console.log(num)
}

