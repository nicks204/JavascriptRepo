//integer array
let numbers = [10, 11, 22, 13, 44, 15, 24];


//printing the array
console.log('Numbers Array: ' + numbers);

//length of the array
let arrLength = numbers.length;
console.log('Length of Numbers Array: ' + arrLength);

//print third element of the array
console.log('Third Element of Numbers Array: ' + numbers[3-1]);

//last element of the array
console.log('Last Element of Numbers Array: ' + numbers[arrLength-1]);

// String array
let names = ['John', 'Jane', 'Jack', 'Jill'];

//printing the array
